import { readFile } from 'node:fs/promises';
import { randomBytes } from 'node:crypto';

const base = new URL('./', import.meta.url);
const token = (await readFile(new URL('build/bridge-token', base), 'utf8')).trim();
const url = JSON.parse(await readFile(new URL('build/stage-result.json', base), 'utf8')).url + '/cv-auth/';
const call = async (action, data = {}, auth = token) => {
  const response = await fetch(url + action, { method: 'POST', headers: { authorization: `Bearer ${auth}`, 'content-type': 'application/json', 'x-cv-client-ip': '192.0.2.49' }, body: JSON.stringify(data) });
  return { status: response.status, data: await response.json() };
};
const expect = (label, actual, wanted) => {
  if (actual !== wanted) throw Error(`${label}: expected ${wanted}, received ${actual}`);
  console.log(`${label}: ${actual}`);
};
const id = randomBytes(6).toString('hex');
const username = `cvqa${id}`;
const password = `Qa!${randomBytes(16).toString('hex')}`;
const nextPassword = `Qb!${randomBytes(16).toString('hex')}`;
const unauthorized = await call('session', { token: 'x' }, 'wrong');
expect('unauthorized', unauthorized.status, 401);
const signup = await call('signup', { username, first_name: 'Test', email: `${username}@example.invalid`, phone: '+971500000000', password, consent: 'yes' });
if (signup.status !== 200) console.log('signup error:', signup.data?.error);
expect('signup', signup.status, 200);
if (!signup.data?.token || !signup.data?.recovery_code) throw Error('Signup omitted token or recovery code');
const duplicate = await call('signup', { username, first_name: 'Test', email: `${username}@example.invalid`, phone: '+971500000000', password, consent: 'yes' });
expect('duplicate', duplicate.status, 409);
const wrong = await call('login', { username, password: 'wrong-password' });
expect('wrong password', wrong.status, 401);
const login = await call('login', { username, password });
expect('login', login.status, 200);
const session = await call('session', { token: login.data.token });
expect('session', session.status, 200);
if (session.data.profile.username !== username) throw Error('Wrong profile owner');
const profile = await call('profile', { token: login.data.token, first_name: 'Updated', email: `${username}@example.invalid`, phone: '+971500000000', city: 'Dubai', craft: 'Art' });
expect('profile', profile.status, 200);
const recovery = await call('recover', { username, recovery_code: signup.data.recovery_code, password: nextPassword });
expect('recovery', recovery.status, 200);
const oldSession = await call('session', { token: login.data.token });
expect('old session revoked', oldSession.status, 401);
const oldPassword = await call('login', { username, password });
expect('old password rejected', oldPassword.status, 401);
const freshLogin = await call('login', { username, password: nextPassword });
expect('new password accepted', freshLogin.status, 200);
const repeat = await call('recover', { username, recovery_code: signup.data.recovery_code, password });
expect('recovery code one use', repeat.status, 401);
const logout = await call('logout', { token: freshLogin.data.token });
expect('logout', logout.status, 200);
const afterLogout = await call('session', { token: freshLogin.data.token });
expect('logout revoked', afterLogout.status, 401);
