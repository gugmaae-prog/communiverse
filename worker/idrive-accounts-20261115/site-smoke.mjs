import { randomBytes } from 'node:crypto';
const base = 'https://communiverseclubs.com';
const override = 'communiverse-workspace-ux-v3-20261009="8b9e7e68-150d-4896-aa1f-2f23169a9aa3"';
const common = process.argv.includes('--public') ? {} : { 'Cloudflare-Workers-Version-Overrides': override };
const id = randomBytes(6).toString('hex');
const username = `cvsitest${id}`;
const password = `Qa!${randomBytes(16).toString('hex')}`;
const expect = (label, got, wanted) => { if (got !== wanted) throw Error(`${label}: expected ${wanted}, got ${got}`); console.log(`${label}: ${got}`); };
const request = (path, data, cookie) => fetch(base + path, { method: data ? 'POST' : 'GET', headers: { ...common, ...(data ? { origin: base, 'content-type': 'application/json' } : {}), ...(cookie ? { cookie } : {}) }, ...(data ? { body: JSON.stringify(data) } : {}), redirect: 'manual' });
const join = await request('/join/');
expect('join page', join.status, 200);
if (!(await join.text()).includes('Create an account')) throw Error('Join form missing');
const signIn = await request('/sign-in/');
expect('sign-in page', signIn.status, 200);
if (!(await signIn.text()).includes('Sign in')) throw Error('Sign-in form missing');
for (const alias of ['/sign-in', '/signin', '/login', '/login/', '/account/login', '/communiverse/account/login']) {
  const redirect = await request(alias);
  expect(`${alias} redirect`, redirect.status, 303);
  if (redirect.headers.get('location') !== '/sign-in/') throw Error(`${alias}: wrong redirect destination`);
}
const created = await request('/account/api/signup', { username, first_name: 'Test', email: `${username}@example.invalid`, phone: '+971500000000', password, confirm_password: password, consent: 'yes' });
expect('site signup', created.status, 200);
const result = await created.json();
if (!result.recovery_code) throw Error('Recovery code missing');
const cookie = created.headers.getSetCookie().find(value => value.startsWith('__Host-cv-account='))?.split(';')[0];
if (!cookie) throw Error('Session cookie missing');
const account = await request('/account/', undefined, cookie);
expect('account page', account.status, 200);
if (!(await account.text()).includes(username)) throw Error('Account page did not show new username');
const profile = await request('/account/api/profile', { first_name: 'Updated', email: `${username}@example.invalid`, phone: '+971500000000', city: 'Dubai', craft: 'Art' }, cookie);
expect('profile update', profile.status, 200);
const logout = await request('/account/api/logout', {}, cookie);
expect('sign out', logout.status, 200);
const signedOut = await request('/account/', undefined, logout.headers.getSetCookie().find(value => value.startsWith('__Host-cv-account='))?.split(';')[0]);
expect('signed-out redirect', signedOut.status, 303);
const login = await request('/account/api/login', { username, password });
expect('site login', login.status, 200);
const loginCookie = login.headers.getSetCookie().find(value => value.startsWith('__Host-cv-account='))?.split(';')[0];
if (!loginCookie) throw Error('Login cookie missing');
const changedPassword = `Qb!${randomBytes(16).toString('hex')}`;
const recovered = await request('/account/api/recover', { username, recovery_code: result.recovery_code, password: changedPassword, confirm_password: changedPassword });
expect('site recovery', recovered.status, 200);
const revoked = await request('/account/', undefined, loginCookie);
expect('prior session revoked', revoked.status, 303);
const oldLogin = await request('/account/api/login', { username, password });
expect('old password rejected', oldLogin.status, 401);
const newLogin = await request('/account/api/login', { username, password: changedPassword });
expect('new password accepted', newLogin.status, 200);
